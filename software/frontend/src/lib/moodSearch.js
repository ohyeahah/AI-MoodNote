const STRIP = /[\s.,!?~…·ㅋㅎㅠㅜ^()'"]+/g;
export const normalize = (s) => String(s ?? '').normalize('NFC').toLowerCase().replace(STRIP, '');

// "격분한" → "격분", "속 편한" → "속편". 어미를 떼고 남은 말이 2글자 이상일 때만 검색어와 견준다.
const koStem = (ko) => normalize(ko).replace(/(스러운|적인|한|운|는|인|은|된|린)$/, '');

// 한 칸 옆(위·아래·왼쪽·오른쪽) 단어. 에너지나 기분이 한 단계 다른, 비슷한 감정이다.
// 구역(색)이 다른 옆 칸은 느낌이 꽤 달라서(예: 피곤한 ↔ 여유로운) 같은 구역의 이웃만 쓴다.
function neighbors(w, byPos) {
  return [[-1, 0], [1, 0], [0, -1], [0, 1]]
    .map(([dr, dc]) => byPos[`${w.grid_row + dr},${w.grid_col + dc}`])
    .filter((n) => n && n.zone === w.zone);
}

// words: 서버의 mood_words (id, word_ko, word_en, grid_row, grid_col, zone ...)
// 돌려주는 값: { best: 검색어와 같거나 가장 가까운 단어들, similar: 비슷한 단어들 }
export function searchMoods(raw, words, { maxBest = 4, maxSimilar = 4 } = {}) {
  const q = normalize(raw);
  if (!q || !words?.length) return { best: [], similar: [] };

  const byId = Object.fromEntries(words.map((w) => [w.id, w]));
  const byPos = Object.fromEntries(words.map((w) => [`${w.grid_row},${w.grid_col}`, w]));
  const score = new Map();
  const add = (id, s) => { if (byId[id] && s > (score.get(id) || 0)) score.set(id, s); };

  // 1) 단어 자체
  const ascii = /^[a-z]+$/.test(q);
  for (const w of words) {
    const ko = normalize(w.word_ko);
    const en = w.word_en.toLowerCase().replace(/\s+/g, '');
    if (ko === q || en === q) { add(w.id, 100); continue; }
    if (q.length >= 2 && ko.includes(q)) { add(w.id, 85); continue; }
    if (ascii && q.length >= 3 && en.startsWith(q)) { add(w.id, 80); continue; }
    const stem = koStem(w.word_ko);
    if (stem.length >= 2 && q.includes(stem)) add(w.id, 90);
  }

  // 2) 일상 표현 사전
  for (const [keys, ids] of DICTIONARY) {
    const hit = keys.some((k) => (k.startsWith('=') ? q === k.slice(1) : q.includes(k)));
    if (!hit) continue;
    ids.forEach((id, i) => add(id, 95 - i * 8));
  }

  // 3) 가장 가까운 단어 둘의 이웃 칸
  const ranked = [...score.entries()].sort((a, b) => b[1] - a[1]);
  for (const [id] of ranked.slice(0, 2)) {
    neighbors(byId[id], byPos).forEach((n) => add(n.id, 40));
  }

  const all = [...score.entries()].sort((a, b) => b[1] - a[1] || a[0] - b[0]).map(([id, s]) => ({ w: byId[id], s }));
  const best = all.filter((x) => x.s >= 70).slice(0, maxBest).map((x) => x.w);
  const bestIds = new Set(best.map((w) => w.id));
  const similar = all.filter((x) => !bestIds.has(x.w.id)).slice(0, maxSimilar).map((x) => x.w);
  return { best, similar };
}
